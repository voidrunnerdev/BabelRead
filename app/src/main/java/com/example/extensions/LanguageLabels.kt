internal fun languageCode(label: String): String? {
    val key = label.trim().lowercase().replace("\u0307", "")
    return when (key) {
        "türkçe", "turkish", "tr" -> "tr"
        "ingilizce", "english", "en" -> "en"
        "fransızca", "french", "fr" -> "fr"
        "ispanyolca", "spanish", "es" -> "es"
        "çince", "chinese", "zh" -> "zh"
        "korece", "korean", "ko" -> "ko"
        "japonca", "japanese", "ja" -> "ja"
        "almanca", "german", "de" -> "de"
        "italyanca", "italian", "it" -> "it"
        "rusça", "russian", "ru" -> "ru"
        "portekizce", "portuguese", "pt", "pt-br" -> "pt-br"
        "arapça", "arabic", "ar" -> "ar"
        else -> null
    }
}
